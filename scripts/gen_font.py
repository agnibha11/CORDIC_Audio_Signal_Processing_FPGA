ORDER = " 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ.:-/+=()[]%<>"
assert len(ORDER) == 50 and all(c in GLYPHS for c in ORDER)

def code_of(ch):
    return ORDER.index(ch)

def rows_of(ch):
    g = GLYPHS[ch]
    out = []
    for r in range(8):
        line = g[r] if r < 7 else "     "
        bits = 0
        for c, px in enumerate(line):
            if px == '#':
                bits |= 1 << (7 - 1 - c)   # glyph occupies bits 6..2, bit 7 and 1,0 blank
        out.append(bits)
    return out

def emit_verilog(path):
    L = []
    L.append("`timescale 1ns / 1ps")
    L.append("`default_nettype none")
    L.append("// ============================================================================")
    L.append("//  vga_font.v -- 8x8 bitmap font ROM for the VGA text overlay")
    L.append("//  GENERATED by scripts/gen_font.py -- do not edit by hand.")
    L.append("//  font_row(code, row) returns the 8 pixels of glyph `code` at line `row`")
    L.append("//  (bit 7 = leftmost pixel).  Codes: %s" % ORDER.replace("%", "%%"))
    L.append("// ============================================================================")
    L.append("module vga_font (")
    L.append("    input  wire [5:0] code,")
    L.append("    input  wire [2:0] row,")
    L.append("    output reg  [7:0] bits")
    L.append(");")
    L.append("    always @(*) begin")
    L.append("        case ({code, row})")
    for ch in ORDER:
        c = code_of(ch)
        for r, b in enumerate(rows_of(ch)):
            if b:
                L.append("            {6'd%d, 3'd%d}: bits = 8'b%s;  // '%s'" % (c, r, format(b, '08b'), ch))
    L.append("            default: bits = 8'b00000000;")
    L.append("        endcase")
    L.append("    end")
    L.append("endmodule")
    L.append("`default_nettype wire")
    open(path, "w").write("\n".join(L) + "\n")

def preview(path):
    import numpy as np
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    cols = 10
    rows = (len(ORDER) + cols - 1) // cols
    img = np.zeros((rows * 9, cols * 9), dtype=np.uint8)
    for i, ch in enumerate(ORDER):
        r, c = divmod(i, cols)
        for y, b in enumerate(rows_of(ch)):
            for x in range(8):
                if b & (1 << (7 - x)):
                    img[r * 9 + y, c * 9 + x] = 1
    plt.figure(figsize=(6, 4))
    plt.imshow(img, cmap="gray", interpolation="nearest")
    plt.axis("off")
    plt.title("vga_font.v glyphs")
    plt.savefig(path, dpi=150, bbox_inches="tight")

