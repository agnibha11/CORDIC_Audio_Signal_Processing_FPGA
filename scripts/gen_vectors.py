#!/usr/bin/env python3
"""
Writes golden test vectors from the bit-accurate Python model (hex, 32-bit
two's complement words, read by the test benches with $readmemh):

  cordic_vectors.mem  (tb_cordic_engine)   mode x_in y_in z_in x_out y_out z_out
  awgn_vectors.mem    (tb_awgn_gen)        noise_idx ni nq
  dsp_vectors.mem     (tb_fm_dsp_core)     fc_idx beta_q fm_idx amp mode source noise x_mic
                                           m_ref r m_hat s tone
"""
import os, random
import cordic_model as cm

def h32(v):
    return "%08x" % (v & 0xFFFFFFFF)

def main():
    random.seed(20261025)
    vec = []
    # rotation: angles around the circle, some exact quadrant boundaries
    for k in range(256):
        z = (k << 16) & 0xFFFFFF
        x, y, zo = cm.cordic(cm.X0, 0, z, False)
        vec.append((0, cm.X0, 0, z, x, y, zo))
    for z in (0, 0x400000, 0x800000, 0xC00000, 0x3FFFFF, 0x7FFFFF, 0xBFFFFF, 0xFFFFFF, 1, 0x400001, 0x800001):
        x, y, zo = cm.cordic(cm.X0, 0, z, False)
        vec.append((0, cm.X0, 0, z, x, y, zo))
    # rotation with arbitrary start vectors
    for _ in range(64):
        xi = random.randint(-300000, 300000); yi = random.randint(-300000, 300000); z = random.getrandbits(24)
        x, y, zo = cm.cordic(xi, yi, z, False)
        vec.append((0, xi, yi, z, x, y, zo))
    # vectoring: random vectors in all quadrants + axes + tiny
    pts = [(1 << 19, 0), (0, 1 << 19), (-(1 << 19), 0), (0, -(1 << 19)), (-(1 << 19), 1), (-(1 << 19), -1),
           (16, 16), (-16, 16), (-16, -16), (16, -16), (0, 0), (1, 0), (-1, 0)]
    for (xi, yi) in pts:
        x, y, zo = cm.cordic(xi, yi, 0, True)
        vec.append((1, xi, yi, 0, x, y, zo))
    for _ in range(256):
        xi = random.randint(-524272, 524272); yi = random.randint(-524272, 524272)
        x, y, zo = cm.cordic(xi, yi, 0, True)
        vec.append((1, xi, yi, 0, x, y, zo))
    base = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(base, "..", "CORDIC.srcs", "sim_1", "new", "cordic_vectors.mem")
    with open(out, "w") as f:
        f.write("// %d vectors: mode x_in y_in z_in x_out y_out z_out (generated by gen_vectors.py)\n" % len(vec))
        for v in vec:
            f.write(" ".join(h32(t) for t in v) + "\n")
    print("wrote", len(vec), "vectors to", out)

def awgn_vectors(base):
    gen = cm.Awgn(); vec = []
    for idx in (31, 16, 1, 0, 7, 31, 24):
        for _ in range(64):
            ni, nq = gen.step(idx)
            vec.append((idx, ni, nq))
    out = os.path.join(base, "..", "CORDIC.srcs", "sim_1", "new", "awgn_vectors.mem")
    with open(out, "w") as f:
        f.write("// %d vectors: noise_idx ni nq (generated by gen_vectors.py)\n" % len(vec))
        for v in vec:
            f.write(" ".join(h32(t) for t in v) + "\n")
    print("wrote", len(vec), "vectors to", out)

def dsp_vectors(base):
    """Whole link (transmitter, channel, receiver, audio filters), sample by sample."""
    import math
    core = cm.FMCore(); vec = []
    rnd = random.Random(7)
    #            fc  beta fm amp mode src noise  n
    segs = [    (40,  40,  8, 16, 0,  1,   0,  300),    # FM, tone, clean channel (defaults)
                (40,  40,  8, 16, 0,  1,  16,  300),    # FM, C/N 15 dB
                (40,  40,  8, 16, 1,  1,  11,  300),    # PM (index limited to 2 rad), C/N 20 dB
                (40,  40,  8, 16, 2,  1,   6,  300),    # AM (depth limited to 100 %), C/N 25 dB
                (40,  40,  8, 16, 3,  1,  21,  300),    # bypass (base band), C/N 10 dB
                (20,   9,  4, 24, 1,  0,   0,  300),    # PM, microphone, small index, gain 1.5
                (20,   3,  4, 40, 2,  0,  31,  300),    # AM, microphone, shallow, C/N 0 dB, clipping gain
                (100, 127, 40, 63, 0,  0,  31,  300),   # FM, everything at maximum (aliasing, saturation)
                (1,    0,  1,  0, 0,  0,   3,  200),    # FM, zero index (receiver gain clamps), zero amplitude
                (57,  80, 13, 16, 0,  0,  26,  300) ]   # FM, microphone, C/N 5 dB (below threshold: clicks)
    n = 0
    for (fc, beta, fm, amp, mode, src, noise, cnt) in segs:
        consts = cm.derive_constants(fc, beta, fm, mode)
        for _ in range(cnt):
            x = int(9000 * math.sin(2 * math.pi * 310 * n / cm.FS) + 7000 * math.sin(2 * math.pi * 1370 * n / cm.FS)) + rnd.randint(-300, 300)
            r = core.step(x, dict(mode=mode, source=src, amp=amp, noise=noise), consts)
            vec.append((fc, beta, fm, amp, mode, src, noise, x, r["m_ref"], r["r"], r["m_hat"], r["s"], r["tone"]))
            n += 1
    out = os.path.join(base, "..", "CORDIC.srcs", "sim_1", "new", "dsp_vectors.mem")
    with open(out, "w") as f:
        f.write("// %d vectors: fc beta fm amp mode source noise x_mic | m_ref r m_hat s tone (generated by gen_vectors.py)\n" % len(vec))
        for v in vec:
            f.write(" ".join(h32(t) for t in v) + "\n")
    print("wrote", len(vec), "vectors to", out)

if __name__ == "__main__":
    main()
    base = os.path.dirname(os.path.abspath(__file__))
    awgn_vectors(base)
    dsp_vectors(base)
