#!/usr/bin/env python3
"""
Writes golden test vectors for tb_cordic_engine.v from the bit-accurate
Python model.  Each vector is 7 words (hex, 32-bit two's complement):
    mode  x_in  y_in  z_in  x_out  y_out  z_out
so the test bench reads them with $readmemh into a flat array.
"""
import os, random
import cordic_model as cm

def h32(v):
    return "%08x" % (v & 0xFFFFFFFF)

def main():
    random.seed(20261025)
    vec = []
    # rotation: angles around the circle, some exact quadrant boundaries
    for k in range(256):
        z = (k << 16) & 0xFFFFFF
        x, y, zo = cm.cordic(cm.X0, 0, z, False)
        vec.append((0, cm.X0, 0, z, x, y, zo))
    for z in (0, 0x400000, 0x800000, 0xC00000, 0x3FFFFF, 0x7FFFFF, 0xBFFFFF, 0xFFFFFF, 1, 0x400001, 0x800001):
        x, y, zo = cm.cordic(cm.X0, 0, z, False)
        vec.append((0, cm.X0, 0, z, x, y, zo))
    # rotation with arbitrary start vectors
    for _ in range(64):
        xi = random.randint(-300000, 300000); yi = random.randint(-300000, 300000); z = random.getrandbits(24)
        x, y, zo = cm.cordic(xi, yi, z, False)
        vec.append((0, xi, yi, z, x, y, zo))
    # vectoring: random vectors in all quadrants + axes + tiny
    pts = [(1 << 19, 0), (0, 1 << 19), (-(1 << 19), 0), (0, -(1 << 19)), (-(1 << 19), 1), (-(1 << 19), -1),
           (16, 16), (-16, 16), (-16, -16), (16, -16), (0, 0), (1, 0), (-1, 0)]
    for (xi, yi) in pts:
        x, y, zo = cm.cordic(xi, yi, 0, True)
        vec.append((1, xi, yi, 0, x, y, zo))
    for _ in range(256):
        xi = random.randint(-524272, 524272); yi = random.randint(-524272, 524272)
        x, y, zo = cm.cordic(xi, yi, 0, True)
        vec.append((1, xi, yi, 0, x, y, zo))
    base = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(base, "..", "CORDIC.srcs", "sim_1", "new", "cordic_vectors.mem")
    with open(out, "w") as f:
        f.write("// %d vectors: mode x_in y_in z_in x_out y_out z_out (generated by gen_vectors.py)\n" % len(vec))
        for v in vec:
            f.write(" ".join(h32(t) for t in v) + "\n")
    print("wrote", len(vec), "vectors to", out)

if __name__ == "__main__":
    main()
