#!/usr/bin/env python3
"""
Generates vga_text_rom.v: the static text of the VGA overlay (40 columns x
30 rows of 16x16 px cells).  Dynamic fields (numbers, mode names, flags) are
left blank here and painted by vga_scope_render.v at the column positions
listed below -- keep both in sync.
"""
import os
from gen_font import ORDER

ROWS = {
 0: " CORDIC RADIO LINK ON A CHIP        K=  ",
 1: " ORIGINAL=GREEN  RECOVERED=YELLOW       ",
12: " CHANNEL=CYAN (DAC-A)   TB=X            ",
24: " FC   =       HZ [1/4]  MODE =       [8]",
25: " BETA =          [2/5]  SRC  =       [7]",
26: " FM   =       HZ [3/6]  CNR  =     [9/E]",
27: " AMP  =          [A/B]  HOLD =       [C]",
28: " DEV  =         HZ      STEP =       [F]",
29: " SNR  =    DB           MON  =       [D]",
}
# alternative row 1 when the overlay shows the error instead of the recovered signal
ROW1_ALT = " ORIGINAL=GREEN  ERRORX16=RED           "

FIELDS = """
  row 0  col 38      : last key (hex digit) while a key is held
  row 1  col 36..39  : CLIP
  row 12 col 28      : time base (1/2/4)   col 31..33 : REC   col 36..39 : MUTE
  row 24 col 8..12   : fc  (5)  col 31..33 : mode (3)
  row 25 col 8..13   : beta(6)  col 31..34 : source (4)
  row 26 col 8..12   : fm  (5)  col 31..34 : C/N (4: "24DB" or " OFF")
  row 27 col 8..11   : amp (4)  col 31..34 : hold (4)
  row 28 col 8..14   : dev (7)  col 31..34 : step (4)
  row 29 col 8..9    : snr (2)  col 31..34 : monitor (4)
"""

def code(ch):
    return ORDER.index(ch)

def main():
    for r, s in list(ROWS.items()) + [(1, ROW1_ALT)]:
        assert len(s) == 40, (r, len(s))
    L = []
    L.append("`timescale 1ns / 1ps")
    L.append("`default_nettype none")
    L.append("// ============================================================================")
    L.append("//  vga_text_rom.v -- static text of the VGA overlay (40 x 30 character cells)")
    L.append("//  GENERATED by scripts/gen_text_layout.py -- do not edit by hand.")
    L.append("//  Dynamic fields are painted by vga_scope_render.v at these positions:")
    for line in FIELDS.strip("\n").split("\n"):
        L.append("//" + line)
    L.append("// ============================================================================")
    L.append("module vga_text_rom (")
    L.append("    input  wire [4:0] row,")
    L.append("    input  wire [5:0] col,")
    L.append("    input  wire       alt1,      // 1: row 1 describes the error overlay")
    L.append("    output reg  [5:0] code")
    L.append(");")
    L.append("    always @(*) begin")
    L.append("        code = 6'd0;")
    L.append("        case (row)")
    for r in sorted(ROWS):
        L.append("            5'd%d: begin" % r)
        if r == 1:
            L.append("                if (alt1) begin")
            L.append("                    case (col)")
            for c, ch in enumerate(ROW1_ALT):
                if ch != ' ':
                    L.append("                        6'd%d: code = 6'd%d; // '%s'" % (c, code(ch), ch))
            L.append("                        default: code = 6'd0;")
            L.append("                    endcase")
            L.append("                end else begin")
            indent = "                    "
        else:
            indent = "                "
        L.append(indent + "case (col)")
        for c, ch in enumerate(ROWS[r]):
            if ch != ' ':
                L.append(indent + "    6'd%d: code = 6'd%d; // '%s'" % (c, code(ch), ch))
        L.append(indent + "    default: code = 6'd0;")
        L.append(indent + "endcase")
        if r == 1:
            L.append("                end")
        L.append("            end")
    L.append("            default: code = 6'd0;")
    L.append("        endcase")
    L.append("    end")
    L.append("endmodule")
    L.append("`default_nettype wire")
    base = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(base, "..", "CORDIC.srcs", "sources_1", "new", "vga_text_rom.v")
    open(out, "w").write("\n".join(L) + "\n")
    print("wrote", out)
    print(FIELDS)

if __name__ == "__main__":
    main()
